#!/usr/bin/env bash
set -euo pipefail
if [ "$#" -ne 2 ]; then echo "Usage: bash build_mep.sh /path/to/VVNZRunner /path/to/output.elf" >&2; exit 2; fi
here="$(cd "$(dirname "$0")" && pwd)"
src="$(cd "$1" && pwd)"
out="$2"
cc="${MEP_CC:-mep-elf-gcc}"
readelf="${MEP_READELF:-mep-elf-readelf}"
test "$(git -C "$src" rev-parse HEAD)" = c1b777ad4af230947a6732e8b17295e5f7ed9d41 || { echo "Use VVNZRunner v2.1 tag checkout"; exit 1; }
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
flags=(-nostdlib -std=c99 -mtiny=0 -mabsdiff -maverage -mbitops -mclip -mdiv -mleadz -mminmax -mmult -mrepeat -msatur -mvl64 -mvliw -mcop64 -D__MEP_CONFIG_CP_DATA_BUS_WIDTH=64 -mivc2 -O3 -ffreestanding -fno-builtin -fno-common -I"$src/sample_mep/include" -I"$here")
# Use the original tagged CRT; this packet-only probe has no global symbols
# requiring the sample's symbolic-address assembly transformation. Reject any
# such movu generated by the compiler rather than blindly rewrite it.
for name in crt0 mep_probe; do
  if [ "$name" = crt0 ]; then input="$src/sample_mep/src/crt0.c"; else input="$here/mep_probe.c"; fi
  "$cc" "${flags[@]}" -S "$input" -o "$tmp/$name.s"
  if grep -E '^[[:space:]]*movu[[:space:]]+[^,]+,[[:space:]]*[^0-9-]' "$tmp/$name.s"; then
    echo "Unexpected symbolic movu: inspect MeP compiler output before proceeding" >&2; exit 1
  fi
  "$cc" "${flags[@]}" -c "$tmp/$name.s" -o "$tmp/$name.o"
done
"$cc" -nodefaultlibs -nostdlib -nostartfiles -o "$tmp/probe.elf" "$tmp/crt0.o" "$tmp/mep_probe.o" -lgcc
"$readelf" -h -S -l "$tmp/probe.elf"
python3 "$here/validate_elf.py" "$tmp/probe.elf"
mkdir -p "$(dirname "$out")"
cp "$tmp/probe.elf" "$out"
